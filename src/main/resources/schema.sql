CREATE TABLE roles (
                       id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(20) NOT NULL UNIQUE          -- 'ADMIN' (ROLE_ prefix'i JWT tarafında eklenecek)
);

CREATE TABLE users (
                       id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(50)  NOT NULL UNIQUE,
                       password VARCHAR(100) NOT NULL,            -- BCrypt hash, düz parola DEĞİL
                       enabled  BOOLEAN      NOT NULL,
                       plate    VARCHAR(15)                       -- sadece USER için dolu
);

CREATE TABLE user_roles (
                            user_id BIGINT NOT NULL REFERENCES users(id),
                            role_id BIGINT NOT NULL REFERENCES roles(id),
                            PRIMARY KEY (user_id, role_id)
);

CREATE TABLE violations (
                            id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            plate          VARCHAR(15)    NOT NULL,
                            violation_date DATE           NOT NULL,   -- "date" SQL'de ayrılmış kelime
                            amount         DECIMAL(10, 2) NOT NULL
);
